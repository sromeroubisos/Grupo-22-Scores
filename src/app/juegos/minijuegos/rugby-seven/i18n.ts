/** Traduce un texto: exacto, por patrón, o por partes (separadas por " · " o por oraciones). Si no sabe, lo deja igual. */
export function translate(raw: string): string {
    const s = raw.trim();
    if (!s) return raw;
    const exact = EXACT[s];
    if (exact !== undefined) return exact;
    for (const [re, fn] of PATTERNS) {
        const m = s.match(re);
        if (m) return fn(m);
    }
    const l = loose(s);
    if (l) return l;
    if (s.includes(' · ')) {
        const parts = s.split(' · ');
        const out = parts.map((p) => translate(p));
        if (out.some((p, i) => p !== parts[i])) return out.join(' · ');
    }
    const sentences = s.split(/(?<=[.!?])\s+/);
    if (sentences.length > 1) {
        const out = sentences.map((p) => translate(p));
        if (out.some((p, i) => p !== sentences[i])) return out.join(' ');
    }
    return raw;
}

/* ───────────────────────── aplicar al DOM ───────────────────────── */

const ATTRS = ['aria-label', 'placeholder', 'title', 'alt'] as const;
/** Lo que había antes y lo que pusimos: si el texto cambió por otro lado (React), el original es el nuevo. */
const TEXT_MEMO = new WeakMap<Node, { orig: string; out: string }>();
const ATTR_MEMO = new WeakMap<Element, Record<string, { orig: string; out: string }>>();

function fixText(node: Text) {
    const cur = node.nodeValue ?? '';
    const memo = TEXT_MEMO.get(node);
    const orig = memo && memo.out === cur ? memo.orig : cur;
    const lead = orig.match(/^\s*/)?.[0] ?? '';
    const trail = orig.match(/\s*$/)?.[0] ?? '';
    const out = orig.trim() ? lead + translate(orig) + trail : orig;
    TEXT_MEMO.set(node, { orig, out });
    if (out !== cur) node.nodeValue = out;
}

function fixAttrs(el: Element) {
    let memo = ATTR_MEMO.get(el);
    for (const a of ATTRS) {
        const cur = el.getAttribute(a);
        if (cur === null) continue;
        const m = memo?.[a];
        const orig = m && m.out === cur ? m.orig : cur;
        const out = translate(orig);
        (memo ??= {})[a] = { orig, out };
        if (out !== cur) el.setAttribute(a, out);
    }
    if (memo) ATTR_MEMO.set(el, memo);
}

function walk(root: Node, fn: (n: Node) => void) {
    const tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let n: Node | null = root;
    while (n) {
        fn(n);
        n = tw.nextNode();
    }
}

function applyAll(root: HTMLElement) {
    walk(root, (n) => {
        if (n.nodeType === Node.TEXT_NODE) {
            const p = n.parentElement;
            if (p && !['SCRIPT', 'STYLE'].includes(p.tagName)) fixText(n as Text);
        } else if (n.nodeType === Node.ELEMENT_NODE) fixAttrs(n as Element);
    });
}

function restoreAll(root: HTMLElement) {
    walk(root, (n) => {
        if (n.nodeType === Node.TEXT_NODE) {
            const memo = TEXT_MEMO.get(n);
            if (memo && memo.out === (n as Text).nodeValue) (n as Text).nodeValue = memo.orig;
        } else if (n.nodeType === Node.ELEMENT_NODE) {
            const el = n as Element;
            const memo = ATTR_MEMO.get(el);
            if (!memo) return;
            for (const [a, m] of Object.entries(memo)) if (el.getAttribute(a) === m.out) el.setAttribute(a, m.orig);
        }
    });
}

/** Empieza a traducir lo que haya adentro de `root` (y lo que aparezca después). Devuelve cómo frenarlo y volver al español. */
export function startTranslating(root: HTMLElement): () => void {
    let busy = false;
    let pending = 0;
    const observer = new MutationObserver(() => {
        // Se junta lo que cambió en el mismo cuadro para traducir una sola vez.
        if (pending) return;
        pending = window.setTimeout(() => {
            pending = 0;
            run();
        }, 30);
    });
    const run = () => {
        if (busy) return;
        busy = true;
        observer.disconnect();
        try {
            applyAll(root);
        } finally {
            observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: [...ATTRS] });
            busy = false;
        }
    };
    run();
    return () => {
        observer.disconnect();
        if (pending) window.clearTimeout(pending);
        restoreAll(root);
    };
}
