function loose(s: string): string | null {
    const y = s.match(/^(.+) (\d{4})$/);
    if (y) {
        const t = translate(y[1]);
        if (t !== y[1]) return `${t} ${y[2]}`;
    }
    if (s.endsWith('.') && !s.endsWith('..')) {
        const t = translate(s.slice(0, -1));
        if (t !== s.slice(0, -1)) return `${t}.`;
    }
    return null;
}

